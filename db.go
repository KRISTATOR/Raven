func schemaFor(pg bool) string {
	r := strings.NewReplacer(
		"{{ID}}", "INTEGER PRIMARY KEY",
		"{{NOW}}", "(datetime('now','localtime'))",
		"{{NOCASE}}", " COLLATE NOCASE",
	)
	extra := ""
	if pg {
		r = strings.NewReplacer(
			"{{ID}}", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
			"{{NOW}}", "(to_char(now() AT TIME ZONE 'Europe/Prague','YYYY-MM-DD HH24:MI:SS'))",
			"{{NOCASE}}", "",
		)
		extra = "CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower ON users(lower(username));\n"
	}
	return r.Replace(schemaTemplate) + extra
}

// ---------- database wrapper: same code for SQLite (local) and Postgres (online) ----------

type DB struct {
	*sql.DB
	pg bool
}

type Tx struct {
	*sql.Tx
	pg bool
}

// rebind turns ? placeholders into $1, $2… for Postgres.
func rebind(pg bool, q string) string {
	if !pg || !strings.Contains(q, "?") {
		return q
	}
	var b strings.Builder
	n, inStr := 0, false
	for _, c := range q {
		switch {
		case c == '\'':
			inStr = !inStr
			b.WriteRune(c)
		case c == '?' && !inStr:
			n++
			fmt.Fprintf(&b, "$%d", n)
		default:
			b.WriteRune(c)
		}
	}
	return b.String()
}

func (d *DB) Exec(q string, args ...any) (sql.Result, error) {
	return d.DB.Exec(rebind(d.pg, q), args...)
}
func (d *DB) Query(q string, args ...any) (*sql.Rows, error) {
	return d.DB.Query(rebind(d.pg, q), args...)
}
func (d *DB) QueryRow(q string, args ...any) *sql.Row { return d.DB.QueryRow(rebind(d.pg, q), args...) }
func (d *DB) Begin() (*Tx, error) {
	tx, err := d.DB.Begin()
	return &Tx{tx, d.pg}, err
}

// InsertID runs an INSERT and returns the new row id (RETURNING works in both databases).
func (d *DB) InsertID(q string, args ...any) (int64, error) {
	var id int64
	err := d.QueryRow(q+" RETURNING id", args...).Scan(&id)
	return id, err
}

func (t *Tx) Exec(q string, args ...any) (sql.Result, error) {
	return t.Tx.Exec(rebind(t.pg, q), args...)
}
func (t *Tx) Query(q string, args ...any) (*sql.Rows, error) {
	return t.Tx.Query(rebind(t.pg, q), args...)
}
func (t *Tx) QueryRow(q string, args ...any) *sql.Row { return t.Tx.QueryRow(rebind(t.pg, q), args...) }
func (t *Tx) InsertID(q string, args ...any) (int64, error) {
	var id int64
	err := t.QueryRow(q+" RETURNING id", args...).Scan(&id)
	return id, err
}

func openSQLite(path string) (*DB, error) {
	dsn := "file:" + path + "?_pragma=foreign_keys(1)&_pragma=journal_mode(WAL)&_pragma=busy_timeout(5000)&_pragma=synchronous(NORMAL)&_txlock=immediate"
	sdb, err := sql.Open("sqlite", dsn)
	if err != nil {
		return nil, err
	}
	sdb.SetMaxOpenConns(4)
	db := &DB{sdb, false}
	if _, err := db.DB.Exec(schemaFor(false)); err != nil {
		return nil, fmt.Errorf("schéma databáze: %w", err)
	}
	migrate(db)
	return db, nil
}

var poolerTxPort = regexp.MustCompile(`(\.pooler\.supabase\.com):6543`)
var schemaName = regexp.MustCompile(`^[a-z_][a-z0-9_]*$`)

// openPostgres connects to Postgres (e.g. Supabase). All tables live in their own
// schema (default "raven"), which Supabase does not expose through its public API.
func openPostgres(url string) (*DB, error) {
	// The schema is selected per connection, so use the pooler's session mode.
	url = poolerTxPort.ReplaceAllString(url, "$1:5432")
	cfg, err := pgx.ParseConfig(url)
	if err != nil {
		return nil, fmt.Errorf("neplatná adresa databáze (DATABASE_URL): %w", err)
	}
	cfg.DefaultQueryExecMode = pgx.QueryExecModeSimpleProtocol
	schema := os.Getenv("DB_SCHEMA")
	if !schemaName.MatchString(schema) {
		schema = "raven"
	}
	sdb := stdlib.OpenDB(*cfg, stdlib.OptionAfterConnect(func(ctx context.Context, c *pgx.Conn) error {
		_, _ = c.Exec(ctx, "CREATE SCHEMA IF NOT EXISTS "+schema)
		_, err := c.Exec(ctx, "SET search_path TO "+schema)
		return err
	}))
	sdb.SetMaxOpenConns(5)
	sdb.SetMaxIdleConns(2)
	sdb.SetConnMaxIdleTime(60 * time.Second)
	db := &DB{sdb, true}
	var lastErr error
	for i := 0; i < 3; i++ {
		if _, lastErr = db.DB.Exec(schemaFor(true)); lastErr == nil {
			migrate(db)
			return db, nil
		}
		time.Sleep(time.Duration(i+1) * 400 * time.Millisecond)
	}
	return nil, fmt.Errorf("schéma databáze: %w", lastErr)
}

// migrate adds columns introduced after the first release (safe to run repeatedly).
func migrate(db *DB) {
	add := "ADD COLUMN"
	if db.pg {
		add = "ADD COLUMN IF NOT EXISTS"
	}
	for _, q := range []string{
		"ALTER TABLE users " + add + " email TEXT",
		"ALTER TABLE students " + add + " email TEXT",
	} {
		_, _ = db.DB.Exec(q)
	}
	_, _ = db.DB.Exec(`CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower ON users(lower(email))`)
}

// Settings is the school-wide configuration, editable by the administrator.
type Settings struct {
	SchoolName    string `json:"school_name"`
	LessonLengths []int  `json:"lesson_lengths"`
	DayStart      int    `json:"day_start"`
	DayEnd        int    `json:"day_end"`
	CircleStart   int    `json:"circle_start"`
	CircleEnd     int    `json:"circle_end"`
	LunchStart    int    `json:"lunch_start"`
	LunchEnd      int    `json:"lunch_end"`
	TripWeekday   int    `json:"trip_weekday"` // 1 = Monday … 5 = Friday, 0 = none
	Grades        []int  `json:"grades"`
	SlotStep      int    `json:"slot_step"`
	// Sign-in with Google: e-mail domains decide the role.
	GoogleClientID string `json:"google_client_id"`
	TeacherDomains string `json:"teacher_domains"`
	StudentDomains string `json:"student_domains"`
}

func defaultSettings() Settings {
	return Settings{
		SchoolName:     "Naše škola",
		LessonLengths:  []int{40, 45, 55, 60, 90, 110},
		DayStart:       8*60 + 20,
		DayEnd:         15 * 60,
		CircleStart:    8 * 60,
		CircleEnd:      8*60 + 20,
		LunchStart:     12 * 60,
		LunchEnd:       12*60 + 40,
		TripWeekday:    5,
		Grades:         []int{7, 8, 9},
		SlotStep:       5,
		TeacherDomains: "zsarcha.cz",
		StudentDomains: "montetrida.cz",
	}
}

func (a *App) loadSettings() Settings {
	s := defaultSettings()
	var raw string
	if err := a.db.QueryRow(`SELECT value FROM settings WHERE key='app'`).Scan(&raw); err == nil {
		_ = json.Unmarshal([]byte(raw), &s)
	}
	if len(s.LessonLengths) == 0 {
		s.LessonLengths = defaultSettings().LessonLengths
	}
	if s.SlotStep <= 0 {
		s.SlotStep = 5
	}
	return s
}

func (a *App) saveSettings(s Settings) error {
	b, _ := json.Marshal(s)
	_, err := a.db.Exec(`INSERT INTO settings(key,value) VALUES('app',?) ON CONFLICT(key) DO UPDATE SET value=excluded.value`, string(b))
	return err
}

// ---------- small helpers ----------

func nowStamp() string { return time.Now().Format("2006-01-02 15:04:05") }

func parseDate(s string) (time.Time, bool) {
	t, err := time.ParseInLocation("2006-01-02", s, time.Local)
	return t, err == nil
}

func fmtDate(t time.Time) string { return t.Format("2006-01-02") }

func czDate(s string) string {
	t, ok := parseDate(s)
	if !ok {
		return s
	}
	days := []string{"ne", "po", "út", "st", "čt", "pá", "so"}
	return fmt.Sprintf("%s %d. %d. %d", days[t.Weekday()], t.Day(), int(t.Month()), t.Year())
}

func hm(m int) string { return fmt.Sprintf("%d:%02d", m/60, m%60) }

func nullInt(p *int64) any {
	if p == nil || *p == 0 {
		return nil
	}
	return *p
}

func nullStr(s string) any {
	if strings.TrimSpace(s) == "" {
		return nil
	}
	return s
}

func idsCSV(ids []int64) string {
	parts := make([]string, len(ids))
	for i, id := range ids {
		parts[i] = fmt.Sprint(id)
	}
	return strings.Join(parts, ",")
}

func placeholders(n int) string {
	if n <= 0 {
		return ""
	}
	return strings.TrimSuffix(strings.Repeat("?,", n), ",")
}

func (a *App) isHoliday(date string) (string, bool) {
	var name string
	err := a.db.QueryRow(`SELECT name FROM holidays WHERE date_from<=? AND date_to>=? LIMIT 1`, date, date).Scan(&name)
	return name, err == nil
}

func (a *App) userName(id int64) string {
	var n string
	_ = a.db.QueryRow(`SELECT name FROM users WHERE id=?`, id).Scan(&n)
	return n
}

func (a *App) studentName(id int64) string {
	var f, l string
	_ = a.db.QueryRow(`SELECT first_name,last_name FROM students WHERE id=?`, id).Scan(&f, &l)
	return strings.TrimSpace(f + " " + l)
}

func (a *App) subjectName(id *int64) string {
	if id == nil {
		return ""
	}
	var n string
	_ = a.db.QueryRow(`SELECT name FROM subjects WHERE id=?`, *id).Scan(&n)
	return n
}

func (a *App) audit(uid int64, action, entity string, ids []int64, summary string) {
	_, _ = a.db.Exec(`INSERT INTO audit(user_id,action,entity,ids,summary,at) VALUES(?,?,?,?,?,?)`, uid, action, entity, idsCSV(ids), summary, nowStamp())
}
